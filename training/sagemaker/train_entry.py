"""
SageMaker Training Entry Point
================================
This script runs INSIDE the SageMaker training container on the cloud GPU.

SageMaker mounts data and writes outputs to fixed paths:
  /opt/ml/input/data/training/   ← training images + labels
  /opt/ml/input/data/validation/ ← validation images + labels
  /opt/ml/model/                 ← save weights here (auto-uploaded to S3)
  /opt/ml/output/                ← save logs, metrics, plots here

Hyperparameters are passed via SageMaker and read from /opt/ml/input/config/hyperparameters.json

DO NOT run this locally — use sagemaker/launch_training.py instead.
"""

import json
import os
import shutil
import sys
from pathlib import Path

# ── SageMaker paths (fixed by the platform) ───────────────────────────────────
SM_INPUT_DIR      = Path("/opt/ml/input/data")
SM_MODEL_DIR      = Path("/opt/ml/model")
SM_OUTPUT_DIR     = Path("/opt/ml/output")
SM_HPARAMS_PATH   = Path("/opt/ml/input/config/hyperparameters.json")

# ── Local paths inside container ──────────────────────────────────────────────
DATASET_YAML_PATH = SM_OUTPUT_DIR / "dataset.yaml"


def load_hyperparameters() -> dict:
    """Reads SageMaker hyperparameters. Falls back to defaults if not present."""
    defaults = {
        "model":         "yolov8s.pt",
        "epochs":        "50",
        "batch":         "16",
        "imgsz":         "640",
        "optimizer":     "AdamW",
        "lr0":           "0.001",
        "lrf":           "0.01",
        "warmup_epochs": "3",
        "weight_decay":  "0.0005",
        "patience":      "20",
        "mosaic":        "1.0",
        "mixup":         "0.1",
        "fliplr":        "0.5",
        "degrees":       "5.0",
    }

    if SM_HPARAMS_PATH.exists():
        with open(SM_HPARAMS_PATH) as f:
            raw = json.load(f)
        # SageMaker wraps all values in strings
        defaults.update(raw)
        print(f"[train_entry] Loaded hyperparameters: {defaults}")
    else:
        print("[train_entry] No hyperparameters.json found, using defaults.")

    return defaults


def build_dataset_yaml() -> Path:
    """
    Creates a dataset.yaml pointing at the SageMaker input data directories.
    YOLOv8 requires an absolute path in the YAML.
    """
    train_img_dir = SM_INPUT_DIR / "training"   / "images"
    val_img_dir   = SM_INPUT_DIR / "validation" / "images"

    # Verify data arrived
    for d in [train_img_dir, val_img_dir]:
        if not d.exists():
            print(f"[train_entry] WARNING: Expected data directory not found: {d}")
            print(f"[train_entry] Contents of {d.parent}: {list(d.parent.iterdir()) if d.parent.exists() else 'parent missing'}")

    SM_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    yaml_content = f"""# Auto-generated by SageMaker training entry point
path: {SM_INPUT_DIR}
train: training/images
val:   validation/images

nc: 6
names:
  - dent
  - scratch
  - crack
  - glass shatter
  - lamp broken
  - tire flat
"""
    DATASET_YAML_PATH.write_text(yaml_content)
    print(f"[train_entry] Dataset YAML written to {DATASET_YAML_PATH}")
    return DATASET_YAML_PATH


def run_training(hp: dict, data_yaml: Path) -> Path:
    """Runs YOLOv8 fine-tuning and returns path to best.pt."""
    try:
        from ultralytics import YOLO
        import torch
    except ImportError as e:
        print(f"[train_entry] FATAL: Missing dependency: {e}")
        sys.exit(1)

    # Detect GPU
    if torch.cuda.is_available():
        device = "cuda"
        print(f"[train_entry] GPU detected: {torch.cuda.get_device_name(0)}")
    else:
        device = "cpu"
        print("[train_entry] WARNING: No GPU detected, training on CPU")

    model_name = hp["model"]
    print(f"[train_entry] Loading model: {model_name}")
    model = YOLO(model_name)

    # Training output goes to /opt/ml/output/train/
    project  = str(SM_OUTPUT_DIR / "train")
    run_name = "cardd_finetune"

    print(f"[train_entry] Starting training: epochs={hp['epochs']}, batch={hp['batch']}, imgsz={hp['imgsz']}")

    results = model.train(
        data=str(data_yaml),
        epochs=int(hp["epochs"]),
        batch=int(hp["batch"]),
        imgsz=int(hp["imgsz"]),
        device=device,
        project=project,
        name=run_name,

        # Optimiser
        optimizer=hp["optimizer"],
        lr0=float(hp["lr0"]),
        lrf=float(hp["lrf"]),
        warmup_epochs=float(hp["warmup_epochs"]),
        weight_decay=float(hp["weight_decay"]),

        # Early stopping
        patience=int(hp["patience"]),

        # Augmentation
        mosaic=float(hp["mosaic"]),
        mixup=float(hp["mixup"]),
        fliplr=float(hp["fliplr"]),
        degrees=float(hp["degrees"]),
        hsv_h=0.015,
        hsv_s=0.7,
        hsv_v=0.4,
        translate=0.1,
        scale=0.5,
        flipud=0.0,

        # Output
        save=True,
        save_period=10,
        val=True,
        plots=True,
        verbose=True,
    )

    best_pt = Path(project) / run_name / "weights" / "best.pt"
    return best_pt, results


def copy_outputs_to_model_dir(best_pt: Path) -> None:
    """
    Copies best.pt to /opt/ml/model/ — SageMaker automatically uploads
    everything in this directory to S3 after training completes.
    """
    SM_MODEL_DIR.mkdir(parents=True, exist_ok=True)

    # Copy weights
    shutil.copy2(best_pt, SM_MODEL_DIR / "best.pt")
    shutil.copy2(best_pt.parent / "last.pt", SM_MODEL_DIR / "last.pt")
    print(f"[train_entry] ✓ Weights copied to {SM_MODEL_DIR}")

    # Copy training plots and metrics
    plots_src = best_pt.parent.parent
    plots_dst = SM_MODEL_DIR / "training_artifacts"
    if plots_src.exists():
        shutil.copytree(str(plots_src), str(plots_dst), dirs_exist_ok=True)
        print(f"[train_entry] ✓ Training artifacts copied to {plots_dst}")


def save_metrics(results) -> None:
    """Saves final metrics as metrics.json for SageMaker experiment tracking."""
    try:
        rd = results.results_dict
        metrics = {
            "mAP50":     round(rd.get("metrics/mAP50(B)",    0.0), 4),
            "mAP50_95":  round(rd.get("metrics/mAP50-95(B)", 0.0), 4),
            "precision": round(rd.get("metrics/precision(B)", 0.0), 4),
            "recall":    round(rd.get("metrics/recall(B)",    0.0), 4),
        }
        metrics_path = SM_MODEL_DIR / "metrics.json"
        with open(metrics_path, "w") as f:
            json.dump(metrics, f, indent=2)
        print(f"[train_entry] Metrics: {metrics}")
        print(f"[train_entry] ✓ metrics.json saved to {metrics_path}")
    except Exception as e:
        print(f"[train_entry] WARNING: Could not save metrics: {e}")


def main():
    print("\n[train_entry] ── ClaimLens YOLOv8 SageMaker Training ──────────────")

    hp       = load_hyperparameters()
    data_yaml = build_dataset_yaml()
    best_pt, results = run_training(hp, data_yaml)

    copy_outputs_to_model_dir(best_pt)
    save_metrics(results)

    print("\n[train_entry] ── Training Complete ────────────────────────────────")
    print(f"[train_entry] best.pt saved → {SM_MODEL_DIR / 'best.pt'}")
    print("[train_entry] SageMaker will upload /opt/ml/model/ to S3 automatically.")


if __name__ == "__main__":
    main()
